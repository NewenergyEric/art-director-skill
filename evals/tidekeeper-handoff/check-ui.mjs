import assert from 'node:assert/strict';
import {createState,act,gameMarkup} from '../../examples/tidekeeper-handoff/references/ui-kit.js';
const initial=createState();
assert.equal(initial.board.length,56);
assert.equal(initial.board.filter(x=>x==='locked').length,14);
assert.match(gameMarkup(initial),/data-action="deliver" disabled/);
let state=act(act(initial,'cell',5),'cell',12);
assert.equal(initial.board[5],3,'actions must not mutate frozen inputs');
assert.equal(state.board[5],null);
assert.equal(state.board[12],4);
assert.doesNotMatch(gameMarkup(state),/data-action="deliver" disabled/);
state=act(state,'deliver');
assert.equal(state.coins,150);
assert.ok(!state.board.includes(4),'delivery consumes one target');
assert.match(gameMarkup(act(state,'map')),/src="workshop-before-portrait.jpg"/);
assert.equal(act(state,'deliver').coins,150,'a completed order cannot pay twice');
state=act(state,'repair');
assert.equal(state.coins,175);
assert.equal(state.board.filter(x=>x==='locked').length,7);
assert.match(gameMarkup(act(state,'map')),/src="workshop-after-portrait.jpg"/);
let wood=act(act(initial,'cell',2),'cell',9);
assert.equal(wood.board[9],'w2');
let mismatch=act(act(initial,'cell',0),'cell',2);
assert.equal(mismatch.board[0],1);assert.equal(mismatch.board[2],'w1');
let moved=act(act(initial,'cell',0),'cell',6);
assert.equal(moved.board[0],null);assert.equal(moved.board[6],1);
let produced=act(initial,'cell',21);
assert.equal(produced.energy,19);assert.equal(produced.board.filter(x=>x===null).length,initial.board.filter(x=>x===null).length-1);
assert.equal(act({...initial,energy:0},'cell',21).energy,0);
let full={...initial,board:initial.board.map(x=>x===null?1:x)};
assert.equal(act(full,'cell',21).energy,20,'full board must not consume energy');
assert.deepEqual(act(initial,'cell',42).board,initial.board,'locked cell does not mutate');
assert.ok(!gameMarkup({...initial,title:'<script>alert(1)</script>'}).includes('<script>'));
console.log('PASS: merge, two orders, inventory, rewards, unlock, production, limits, relocation-safe URLs and escaped text.');
